export const elemMult = (a, d) =>
  !a || !d ? 1 : ELEM[a].beats === d ? 1.5 : ELEM[d].beats === a ? 0.75 : 1;

/** 地域データ → ステータス補正 */
export function mods(p) {
  return {
    def: 1 + (p.peak / 3776) * 0.5, // 標高が高いほど防御UP（富士山で×1.5）
    spd: 1 + (p.forest - 30) / 100, // 森林率（地形の険しさ）で素早さUP
    hp: 1 + p.foodIdx / 250, // グルメ指数でHP UP
    sk: 1 + p.foodIdx / 200, // グルメ指数で必殺技の威力UP
    lv: Math.round(((REGIONS.length + 1 - p.rank) / REGIONS.length) * 2), // 魅力度上位ほどレベル上乗せ
  };
}

// エリアごとに Lv が 4 ずつ上がる（城の数が少ないぶん、1ステージの上がり幅を大きくしている）
export const enemyLevel = (p) => Math.round(1 + p.id * 4) + mods(p).lv;

/** レベルと地方データからステータスを計算（p が null なら主人公） */
export function stats(L, p, scale) {
  const m = p ? mods(p) : { def: 1, spd: 1, hp: 1, sk: 1.3 };
  return {
    hp: Math.round((50 + 11 * L) * m.hp * scale),
    atk: Math.round((9 + 2.4 * L) * scale),
    def: Math.round((5 + 1.3 * L) * m.def * scale),
    spd: Math.round((6 + 0.6 * L) * m.spd * 10) / 10,
    sk: m.sk,
  };
}

